CREATE TABLE obzors (
  id         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  question   TEXT NOT NULL,
  opens_at   TIMESTAMPTZ NOT NULL,
  closes_at  TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE obzor_items (
  id       BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  obzor_id BIGINT NOT NULL REFERENCES obzors(id) ON DELETE CASCADE,
  name     TEXT NOT NULL,
  book     TEXT NOT NULL DEFAULT '',
  details  TEXT NOT NULL DEFAULT ''
);

-- one order per person per review: item ids from the top (the most) down
CREATE TABLE obzor_votes (
  user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  obzor_id   BIGINT NOT NULL REFERENCES obzors(id) ON DELETE CASCADE,
  item_ids   BIGINT[] NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, obzor_id)
);

-- comments, opened in the archive, moderated in the bot
CREATE TABLE obzor_comments (
  id         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  obzor_id   BIGINT NOT NULL REFERENCES obzors(id) ON DELETE CASCADE,
  user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  text       TEXT NOT NULL CHECK (char_length(text) BETWEEN 3 AND 300),
  status     TEXT NOT NULL DEFAULT 'pending',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

